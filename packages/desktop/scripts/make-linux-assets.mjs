#!/usr/bin/env node
/**
 * The two files no packaging tool will write for us.
 *
 *   build/linux/generated/dev.piorbit.desktop.metainfo.xml
 *       AppStream. Without it piorbit appears in GNOME Software and KDE
 *       Discover as a bare package name with no description and no icon —
 *       which is how a native application is told apart from something that
 *       was dropped on the machine.
 *
 *   build/linux/generated/piorbit.desktop
 *       The menu entry for the tarball. The deb, the rpm and the AppImage get
 *       theirs from electron-builder's `linux.desktop` block; a tarball has no
 *       packaging step to generate one, so it ships its own.
 *
 * Both are validated by `scripts/build-linux.mjs` with desktop-file-validate
 * and appstreamcli when those exist on the build machine.
 *
 *   node scripts/make-linux-assets.mjs
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  APP_ID,
  BRANDING,
  CATEGORIES,
  DESCRIPTION,
  DESCRIPTION_MORE,
  DESCRIPTION_RELAY,
  EXECUTABLE,
  HOMEPAGE,
  ICON_SIZES,
  KEYWORDS,
  METADATA_LICENSE,
  PROJECT_LICENSE,
  SUMMARY,
  URL_SCHEME,
} from "../build/linux/product.mjs";

const packageRoot = dirname(fileURLToPath(new URL("../package.json", import.meta.url)));
const generatedDir = join(packageRoot, "build", "linux", "generated");
const version = JSON.parse(readFileSync(join(packageRoot, "package.json"), "utf8")).version;

/**
 * electron-builder.yml cannot import product.mjs, and product.mjs cannot parse
 * YAML without a dependency. So instead of a parser, an assertion: the two
 * files must literally contain the same sentences, and the build stops the day
 * one of them is edited alone.
 */
function assertBuilderConfigAgrees() {
  const configPath = join(packageRoot, "electron-builder.yml");
  const config = readFileSync(configPath, "utf8");
  // A YAML folded scalar (`>-`) wraps the description across lines, so compare
  // word by word rather than character by character.
  const flattened = config.replace(/\s+/g, " ");
  const drift = [
    ["synopsis", SUMMARY],
    ["description", DESCRIPTION],
  ].filter(([, text]) => !flattened.includes(text.replace(/\s+/g, " ")));
  if (drift.length > 0) {
    throw new Error(
      `piorbit: ${configPath} and build/linux/product.mjs disagree about ${drift
        .map(([field]) => `linux.${field}`)
        .join(" and ")}.\n` +
        `Package descriptions come from product.mjs; copy the text below into electron-builder.yml so a\n` +
        `person reading the deb, the rpm, the AppImage and GNOME Software is told the same thing:\n\n` +
        drift.map(([field, text]) => `  ${field}: ${JSON.stringify(text)}`).join("\n"),
    );
  }
}

/**
 * A date that is the same for everyone who builds this commit. AppStream wants
 * one on every release, and `new Date()` would make two builds of one tag
 * differ (M10-T7 asks for a release that is reproducible from a tag).
 */
function releaseDate() {
  if (process.env.SOURCE_DATE_EPOCH) {
    return new Date(Number(process.env.SOURCE_DATE_EPOCH) * 1000).toISOString().slice(0, 10);
  }
  try {
    return execFileSync("git", ["log", "-1", "--format=%cs"], { cwd: packageRoot, encoding: "utf8" }).trim();
  } catch {
    return new Date().toISOString().slice(0, 10);
  }
}

const escapeXml = (value) =>
  value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/**
 * Screenshots are URLs, not files: AppStream clients fetch them over HTTPS.
 * There is nowhere public to serve them from until M10-T7 stands a download
 * host up, and pointing at a URL that 404s would put a broken image in GNOME
 * Software — worse than none. So the block is emitted only when the host is
 * named, and its absence is announced rather than hidden.
 */
function screenshots() {
  const base = process.env.PIORBIT_SCREENSHOT_BASE_URL;
  if (!base) {
    console.log(
      "piorbit: no PIORBIT_SCREENSHOT_BASE_URL, so the metainfo ships without screenshots.\n" +
        "         Set it to a public HTTPS directory holding session.png and phone.png to include them.",
    );
    return "";
  }
  const trimmed = base.replace(/\/$/, "");
  return `
  <screenshots>
    <screenshot type="default">
      <caption>A session in progress, with the agent's plan beside its work</caption>
      <image type="source">${escapeXml(`${trimmed}/session.png`)}</image>
    </screenshot>
    <screenshot>
      <caption>The same session mirrored to a phone over the encrypted relay</caption>
      <image type="source">${escapeXml(`${trimmed}/phone.png`)}</image>
    </screenshot>
  </screenshots>
`;
}

const metainfo = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/make-linux-assets.mjs — do not edit by hand. -->
<component type="desktop-application">
  <id>${APP_ID}</id>
  <launchable type="desktop-id">${EXECUTABLE}.desktop</launchable>
  <name>${escapeXml(EXECUTABLE)}</name>
  <summary>${escapeXml(SUMMARY)}</summary>
  <metadata_license>${METADATA_LICENSE}</metadata_license>
  <project_license>${PROJECT_LICENSE}</project_license>
  <developer id="dev.piorbit">
    <name>piorbit contributors</name>
  </developer>
  <description>
    <p>${escapeXml(DESCRIPTION)}</p>
    <p>${escapeXml(DESCRIPTION_MORE)}</p>
    <p>${escapeXml(DESCRIPTION_RELAY)}</p>
  </description>
  <categories>
${CATEGORIES.map((category) => `    <category>${category}</category>`).join("\n")}
  </categories>
  <keywords>
${KEYWORDS.map((keyword) => `    <keyword>${escapeXml(keyword)}</keyword>`).join("\n")}
  </keywords>
  <provides>
    <binary>${EXECUTABLE}</binary>
  </provides>
  <url type="homepage">${escapeXml(HOMEPAGE)}</url>
  <url type="bugtracker">${escapeXml(`${HOMEPAGE}/issues`)}</url>
  <branding>
    <color type="primary" scheme_preference="light">${BRANDING.light}</color>
    <color type="primary" scheme_preference="dark">${BRANDING.dark}</color>
  </branding>
  <content_rating type="oars-1.1"/>
  <releases>
    <release version="${version}" date="${releaseDate()}"/>
  </releases>${screenshots()}
</component>
`;

/**
 * The tarball's menu entry. `Exec` is rewritten to an absolute path by the
 * tarball's own install.sh, which is the only thing that knows where the person
 * unpacked it; the value here is the one that works when ~/.local/bin is on
 * PATH, so the file is valid and launchable as shipped.
 */
const desktopEntry = `[Desktop Entry]
Name=${EXECUTABLE}
Comment=${SUMMARY}
Exec=${EXECUTABLE} %U
Icon=${EXECUTABLE}
Terminal=false
Type=Application
StartupNotify=true
StartupWMClass=${EXECUTABLE}
Categories=${CATEGORIES.join(";")};
Keywords=${KEYWORDS.join(";")};
MimeType=x-scheme-handler/${URL_SCHEME};
X-GNOME-UsesNotifications=true
`;

assertBuilderConfigAgrees();
mkdirSync(generatedDir, { recursive: true });
writeFileSync(join(generatedDir, `${APP_ID}.metainfo.xml`), metainfo);
writeFileSync(join(generatedDir, `${EXECUTABLE}.desktop`), desktopEntry);
process.stdout.write(
  `piorbit linux assets: build/linux/generated/${APP_ID}.metainfo.xml, ` +
    `build/linux/generated/${EXECUTABLE}.desktop (icons: ${ICON_SIZES.join(", ")})\n`,
);
